// SuppliedTable pairs the supplied weighting with the supplied paytable for one
// board. Its return is whatever the vendor shipped (see docs/games/plinko-rtp.md §5).
func SuppliedTable(params Params) (Table, error) {
	if err := params.Validate(); err != nil {
		return Table{}, err
	}
	return Table{
		Weights:               SuppliedWeights[params.Rows],
		MultipliersHundredths: SuppliedMultipliersHundredths[params.Rows][params.Risk],
	}, nil
}
